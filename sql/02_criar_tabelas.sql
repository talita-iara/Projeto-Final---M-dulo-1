CREATE TABLE public.tratada_vendas (
	id_venda varchar(50) NOT NULL,
	filial varchar(10) NOT NULL,
	cidade varchar(100) NOT NULL,
	tipo_cliente varchar(50) NULL,
	genero varchar(50) NULL,
	linha_produto varchar(150) NOT NULL,
	preco_unitario numeric(10, 2) NOT NULL,
	quantidade int4 NOT NULL,
	imposto numeric(10, 2) NOT NULL,
	valor_total numeric(12, 2) NOT NULL,
	data_venda date NOT NULL,
	hora_venda time(6) NOT NULL,
	forma_pagamento varchar(50) NOT NULL,
	custo_mercadoria numeric(12, 2) NOT NULL,
	margem_percentual numeric(10, 2) NULL,
	receita_bruta numeric(12, 2) NOT NULL,
	avaliacao numeric(4, 2) NOT NULL,
	CONSTRAINT tratada_vendas_pkey PRIMARY KEY (id_venda),
	CONSTRAINT preco_unitario CHECK ((preco_unitario >= (0)::numeric)) NOT VALID,
	CONSTRAINT quantidade CHECK ((quantidade > 0)) NOT VALID,
	CONSTRAINT "Imposto" CHECK ((imposto >= (0)::numeric)) NOT VALID,
	CONSTRAINT valor_total CHECK ((valor_total >= (0)::numeric)) NOT VALID,
	CONSTRAINT custo_mercadoria CHECK ((custo_mercadoria >= (0)::numeric)) NOT VALID,
	CONSTRAINT receita_bruta CHECK ((receita_bruta >= (0)::numeric)) NOT VALID,
	CONSTRAINT avaliacao CHECK (((avaliacao >= (0)::numeric) AND (avaliacao <= (10)::numeric))) NOT VALID
)